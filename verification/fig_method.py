import numpy as np, matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
fig,(a,b)=plt.subplots(1,2,figsize=(7.6,3.3),gridspec_kw={'width_ratios':[1.15,1]})
a.axvspan(0,1,color='#e9e2d0'); a.axvspan(7/8,2.3,color='#cfe0f2')
a.axvline(0.5,color='#888',lw=0.8,ls=':'); a.axvline(7/8,color='#1f4e9c',lw=1.2)
rng=np.random.default_rng(3); g=np.sort(rng.uniform(-9,9,26)); bt=rng.uniform(0.18,0.82,26)
a.plot(bt,g,'o',ms=3.5,color='#b8461b'); a.plot(1-bt,g,'o',ms=3.5,color='#b8461b',alpha=0.45)
a.annotate('',xy=(2.25,0),xytext=(1,0),arrowprops=dict(arrowstyle='->',lw=2,color='k'))
a.plot([1],[0],'ks',ms=5); a.text(1.05,0.6,r'$s=1+u$, $u\geq0$',fontsize=8.5)
a.text(0.9,7.6,r'Re $s>7/8$: no zeros',fontsize=8.5,color='#1f4e9c')
a.text(0.02,-9.6,'critical strip',fontsize=8)
a.set_xlim(-0.3,2.3); a.set_ylim(-10,10); a.set_xlabel(r'Re $s$'); a.set_ylabel(r'Im $s$')
a.set_title('(a) zeros and the ray of integration',fontsize=9)
y,x=1e5,1e5*np.exp(3); n=np.logspace(3,np.log10(x*3),600)
w=np.where(n<=y,1,np.where(n<=x,np.log(x/n)/np.log(x/y),0))
b.semilogx(n,w,color='#1f4e9c',lw=2); b.axvline(y,color='#888',lw=0.7,ls=':'); b.axvline(x,color='#888',lw=0.7,ls=':')
b.text(y*1.1,1.04,r'$y$',fontsize=9); b.text(x*1.1,1.04,r'$x=\lambda y$',fontsize=9)
b.set_ylim(-0.05,1.15); b.set_xlabel(r'$n$'); b.set_ylabel(r'$w(n)$')
b.set_title(r'(b) the weight $w(n)$',fontsize=9)
fig.tight_layout()
for e in ['png','pdf']: fig.savefig('../paper/figures/fig_method.'+e,dpi=200)
